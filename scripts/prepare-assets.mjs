import { readFile, writeFile, readdir, mkdir, stat, access } from 'node:fs/promises';
import { resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
import { localize } from '../static/js/core/content.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'media/optimized');
await mkdir(output, { recursive: true });
await mkdir(resolve(root, 'static/js/generated'), { recursive: true });
await mkdir(resolve(root, 'static/css/generated'), { recursive: true });
const readJSON = async path => JSON.parse(await readFile(resolve(root, path), 'utf8'));
const meta = await readJSON('data/meta.json');
const images = {};
const report = [];
async function scan(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name === 'optimized' || entry.name.startsWith('.')) continue;
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await scan(path));
    else if (/\.(png|jpe?g|webp)$/i.test(entry.name) && (await stat(path)).size > 16384) files.push(path);
  }
  return files;
}
for (const path of (await scan(resolve(root, 'media'))).concat(await scan(resolve(root, 'blogs'))).sort()) {
  const source = relative(root, path).split('\\').join('/');
  const raw = await readFile(path);
  const metadata = await sharp(raw).metadata();
  if (metadata.pages > 1) continue; // Animated assets must keep their animation.
  const rotated = [5, 6, 7, 8].includes(metadata.orientation);
  const width = rotated ? metadata.height : metadata.width;
  const height = rotated ? metadata.width : metadata.height;
  const hash = createHash('sha256').update(raw).update(`webp-q80-v1-${sharp.versions.sharp}`).digest('hex').slice(0, 16);
  const widths = [...new Set([160, 320, 640, 960, 1280, 1920].map(size => Math.min(size, width)))];
  const variants = [];
  for (const size of widths) {
    const name = `${hash}-${size}.webp`;
    const target = resolve(output, name);
    try { await access(target); } catch {
      await sharp(raw).rotate().resize({ width: size, withoutEnlargement: true }).webp({ quality: 80, effort: 5 }).toFile(target);
    }
    variants.push({ width: size, src: `media/optimized/${name}` });
  }
  images[source] = { width, height, variants };
  const sample = variants.find(item => item.width >= 640) || variants.at(-1);
  report.push({ source, originalBytes: raw.length, previewWidth: sample.width, previewBytes: (await stat(resolve(root, sample.src))).size });
}
const navigation = {};
for (const section of meta.sections) {
  const source = section.dataSource || section.id;
  const document = await readJSON(`data/content/${source}.json`);
  navigation[source] = Object.fromEntries(meta.availableLanguages.map(lang => {
    const copy = localize(document, lang, meta.defaultLanguage);
    return [lang, copy.nav_label || copy.title || section.id];
  }));
}
const backgroundSource = meta.backgrounds?.default?.light?.replace(/^\.\//, '');
await writeFile(resolve(root, 'static/js/generated/assets.js'), `// Generated by npm run prepare:assets. Edit original content and images instead.\nexport const images = ${JSON.stringify(images)};\nexport const navigation = ${JSON.stringify(navigation)};\nexport const defaultBackground = ${JSON.stringify(backgroundSource || '')};\n`);
const background = images[backgroundSource];
const choose = width => background.variants.find(item => item.width >= width) || background.variants.at(-1);
const cssImage = width => `image-set(url("../../../${choose(width).src}") 1x, url("../../../${choose(width * 2).src}") 2x)`;
await writeFile(resolve(root, 'static/css/generated/media.css'), background
  ? `/* Generated responsive background; original images remain untouched. */\n:root { --site-default-background: ${cssImage(640)}; }\n@media (min-width: 769px) { :root { --site-default-background: ${cssImage(1280)}; } }\n`
  : `:root { --site-default-background: ${backgroundSource ? `url(${JSON.stringify(/^https?:/i.test(backgroundSource) ? backgroundSource : '../../../' + backgroundSource)})` : 'none'}; }\n`);
// Static hero markup must use the same source set as the JS renderer to avoid
// fetching an original image before the module has run.
for (const page of ['index.html', 'multipage_index.html']) {
  let html = await readFile(resolve(root, page), 'utf8');
  html = html.replace(/<img\b[^>]*data-responsive-source="([^"]+)"[^>]*>/g, (tag, source) => {
    const entry = images[source.replace(/^\.\//, '')];
    if (!entry) return tag;
    const candidates = entry.variants.filter(item => item.width <= 640);
    const fallback = candidates.find(item => item.width >= 320) || candidates.at(-1);
    return tag.replace(/\s(?:src|srcset|sizes)="[^"]*"/g, '')
      .replace(/>$/, ` src="./${fallback.src}" srcset="${candidates.map(item => `./${item.src} ${item.width}w`).join(', ')}" sizes="128px">`);
  });
  await writeFile(resolve(root, page), html);
}
await mkdir(resolve(root, 'artifacts'), { recursive: true });
await writeFile(resolve(root, 'artifacts/image-sizes.json'), JSON.stringify(report, null, 2));
console.log(`Prepared ${report.length} responsive images and ${Object.keys(navigation).length} navigation labels. Originals preserved.`);
